"""Recompile DotR's overlay modules (DATA/CMODULE.MRG, BMODULE.MRG, MMODULE.MRG) for the runtime.

Each module is an "MWo3" blob loaded at 0x1E00000 (header: magic, id, load address, ?, ?, ?, end, end,
name[0x20] at 0x20, code from +0x80). sub_001F4900 copies the 0x8000 slot to 0x1E00000 and calls
ENTRY_TABLES[mrg][N] for module <letter>N.bin; those entries are added as function starts. They all share that address, so every module is recompiled on its own and its
functions are wrapped in a namespace; src/dotr_overlays.cpp picks the table by the id at 0x1E00004 at call time.

usage: overlays.py DISC_DIR WORK_DIR PS2_RECOMP [NAME...]
  DISC_DIR   folder with the extracted disc (SLUS_205.15, DATA/*.MRG)
  WORK_DIR   per-module ELF/CSV/TOML/recompiler output (outside git, e.g. ../dotr/overlays)
  writes WORK_DIR/cpp/ov_<name>.cpp (one translation unit per module; tools/sync_runner.sh copies them)
  NAME...    only these modules (e.g. c400), default all. ps2_recomp runs one module at a time."""
import os, re, struct, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from find_functions import find_starts, write_csv, JR_RA

BASE, ENTRY_OFF = 0x1E00000, 0x80
MRGS = ('CMODULE', 'BMODULE', 'MMODULE')
ENTRY_TABLES = (0x2B9190, 0x2BA140, 0x2BAEA0)   # in SLUS_205.15 (pointed to by the table at 0x292FF0)
MAIN_FILE_BASE = 0x100000 - 0x6900


def modules(disc):
    main = open(os.path.join(disc, 'SLUS_205.15'), 'rb').read()
    for mrg, table in zip(MRGS, ENTRY_TABLES):
        d = open(os.path.join(disc, 'DATA', mrg + '.MRG'), 'rb').read()
        for off in range(0, len(d), 0x800):
            if d[off:off + 4] == b'MWo3':
                mid, load = struct.unpack_from('<2I', d, off + 4)
                end = struct.unpack_from('<I', d, off + 0x1C)[0]
                assert load == BASE and BASE < end <= BASE + 0x8000, hex(load)
                name = d[off + 0x20:off + 0x40].split(b'\0')[0].decode().removesuffix('.bin')
                entry = struct.unpack_from('<I', main, table + 4 * int(name[1:]) - MAIN_FILE_BASE)[0]
                assert BASE + ENTRY_OFF <= entry < end, (name, hex(entry))
                yield name, mid, entry, d[off:off + end - BASE]


def write_elf(path, blob):
    """Minimal ELF32 MIPS LE: one PT_LOAD and one WAX section at BASE (like the main ELF's merged section)."""
    shstr = b'\0.text\0.shstrtab\0'
    code_off = 0x1000
    shoff = code_off + len(blob) + len(shstr)
    shoff = (shoff + 3) & ~3
    eh = struct.pack('<4s5B7x2H5I6H', b'\x7fELF', 1, 1, 1, 0, 0, 2, 8, 1, BASE + ENTRY_OFF, 52, shoff,
                     0x20924001, 52, 32, 1, 40, 3, 2)
    ph = struct.pack('<8I', 1, code_off, BASE, BASE, len(blob), len(blob), 7, 0x10)
    sh = bytes(40)
    sh += struct.pack('<10I', 1, 1, 7, BASE, code_off, len(blob), 0, 0, 0x10, 0)
    sh += struct.pack('<10I', 7, 3, 0, 0, code_off + len(blob), len(shstr), 0, 0, 1, 0)
    out = bytearray(eh + ph)
    out += bytes(code_off - len(out)) + blob + shstr
    out += bytes(shoff - len(out)) + sh
    open(path, 'wb').write(out)


def text_end(blob):
    last = max(i for i in range(ENTRY_OFF, len(blob) - 4, 4) if struct.unpack_from('<I', blob, i)[0] == JR_RA)
    return BASE + last + 8


TOML = '''[general]
input = "{elf}"
ghidra_output = "{csv}"
output = "{out}/"
single_file_output = true
output_worker_threads = 1   # the parallel single-file writer loses entries ("completion queue is missing index")
patch_syscalls = false
patch_cop0 = true
patch_cache = true
stubs = []
'''


def wrap(name, mid, out):
    """Turn ps2_recomp's single-file output into one namespaced translation unit plus a registration entry."""
    src = open(os.path.join(out, 'ps2_recompiled_functions.cpp')).read()
    decls = open(os.path.join(out, 'ps2_recompiled_functions.h')).read()
    reg = open(os.path.join(out, 'register_functions.cpp')).read()
    entries = re.findall(r'\] = (\w+); // 0x([0-9a-f]+)', reg)
    decls = '\n'.join(l for l in decls.splitlines() if l.startswith('void '))
    body = '\n'.join(l for l in src.splitlines() if not l.startswith('#include'))
    includes = '\n'.join(l for l in src.splitlines() if l.startswith('#include') and 'recompiled_functions' not in l)
    table = ',\n'.join(f'    {{0x{a}u, {n}}}' for n, a in sorted(entries, key=lambda e: int(e[1], 16)))
    return f'''// Generated by tools/overlays.py from {name}.bin (overlay id 0x{mid:x}). Do not edit.
{includes}
#include "dotr_overlays.h"
namespace ov_{name} {{
{decls}
{body}
const DotrOverlayEntry kEntries[] = {{
{table}
}};
const DotrOverlayRegistration kRegistration(0x{mid:x}u, kEntries, sizeof(kEntries) / sizeof(kEntries[0]));
}}
'''


def main():
    disc, work, recomp = sys.argv[1:4]
    only = set(sys.argv[4:])
    os.makedirs(os.path.join(work, 'cpp'), exist_ok=True)
    for name, mid, entry, blob in modules(disc):
        if only and name not in only:
            continue
        mdir = os.path.join(work, name)
        out = os.path.join(mdir, 'out')
        os.makedirs(out, exist_ok=True)
        elf, csv, toml = (os.path.join(mdir, name + ext) for ext in ('.elf', '.csv', '.toml'))
        write_elf(elf, blob)
        end = text_end(blob)
        starts, _ = find_starts(blob, BASE, BASE + ENTRY_OFF, BASE + ENTRY_OFF, end, [(end, BASE + len(blob))], {entry})
        write_csv(csv, starts, end)
        open(toml, 'w').write(TOML.format(elf=os.path.abspath(elf), csv=os.path.abspath(csv),
                                          out=os.path.abspath(out)))
        r = subprocess.run([recomp, toml], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f'{name}: ps2_recomp failed\n{r.stdout[-2000:]}{r.stderr[-2000:]}')
        cpp = wrap(name, mid, out)
        dst = os.path.join(work, 'cpp', f'ov_{name}.cpp')
        if not os.path.exists(dst) or open(dst).read() != cpp:
            open(dst, 'w').write(cpp)
        print(f'{name} id=0x{mid:x} functions={len(starts)} code=0x{end - BASE:x}', flush=True)


if __name__ == '__main__':
    main()
